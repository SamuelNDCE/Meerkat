#!/usr/bin/env node
// Writes docs/accuracy-results.md (and docs/readme-accuracy-section.md) from the output of a corpus run, so no number is typed by hand.
//   node tools/accuracy-corpus.mjs --run --discover > run.txt        (the run; slow, done separately)
//   node tools/gen-accuracy-results.mjs run.txt [--out docs/accuracy-results.md] [--readme docs/readme-accuracy-section.md]
// It only READS the run output; it never runs the corpus. Tier comes from tools/accuracy-tiers.mjs, suite from the registry (same as the corpus).
// Run output lines used:  "OK   project:key [check/rule] file:line => found..."  and  "MISS ..." (from --discover),
// plus optional clean-twin lines "FALSE-ALARM project check/rule file:line" (none are printed today; the report then says so).
import { readFileSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { TIER_NAMES, tierOf } from './accuracy-tiers.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const pct = (n, d) => (d ? `${((n / d) * 100).toFixed(1)}%` : 'n/a')

export function parseRun(text) {
  const rows = []
  const cleanProjects = new Set()
  const falseAlarms = []
  let totalLine = null
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trimEnd()
    let m = /^(OK|MISS)\s+(\S+?):(\S+) \[([^\]]*)\] (.*?):(\d+) =>/.exec(line)
    if (m) {
      const [, status, project, key, expected, file, ln] = m
      rows.push({ status, project, key, expected, file, line: Number(ln) })
      continue
    }
    m = /^running (\S+-clean)\s*$/.exec(line)
    if (m) cleanProjects.add(m[1])
    m = /^FALSE-ALARM\s+(.*)$/.exec(line)
    if (m) falseAlarms.push(m[1])
    m = /^FALSE-ALARM-TOTAL\s+(\d+) across (\d+) twins\s*$/.exec(line)
    if (m) totalLine = { total: Number(m[1]), twins: Number(m[2]) }
  }
  const perTwin = {}
  for (const f of falseAlarms) perTwin[f.split(/\s+/)[0]] = (perTwin[f.split(/\s+/)[0]] ?? 0) + 1
  return { rows, cleanProjects: [...cleanProjects], falseAlarms, perTwin, totalLine, falseAlarmsRecorded: /^FALSE-ALARM|^CLEAN-TWINS/m.test(text) }
}

// Suite of a check, by the same registry lookup the corpus uses (withSuites there also demands a tier, which a bare check has none of).
let registry
async function suiteOf(check) {
  if (!registry) {
    const { pathToFileURL } = await import('node:url')
    const { suiteIdOf } = await import(pathToFileURL(join(ROOT, 'lib', 'suites.mjs')).href)
    const { allCheckIds } = await import(pathToFileURL(join(ROOT, 'tools', 'compat-matrix.mjs')).href)
    registry = { suiteIdOf, packOf: new Map((await allCheckIds()).map((c) => [c.id, c.pack])) }
  }
  try {
    return registry.suiteIdOf({ id: check, pack: registry.packOf.get(check) })
  } catch {
    return 'other'
  }
}

export async function build(text) {
  const run = parseRun(text)
  const cache = new Map()
  for (const r of run.rows) {
    const c = r.expected.split('/')[0]
    if (!cache.has(c)) cache.set(c, await suiteOf(c))
    r.suite = cache.get(c)
    r.tier = tierOf(r.key) ?? 'untiered'
  }
  return run
}

const tally = (rows) => ({ planted: rows.length, found: rows.filter((r) => r.status === 'OK').length })

export function render(data, sourceName) {
  const { rows } = data
  const all = tally(rows)
  const L = []
  L.push('# Planted-bug accuracy: results', '')
  L.push(`Generated by \`node tools/gen-accuracy-results.mjs ${sourceName}\` from a corpus run (\`node tools/accuracy-corpus.mjs --run --discover\`). Do not edit by hand; regenerate it after each run.`, '')
  L.push('**Recall on planted bugs measures what was planted, not real-world accuracy.** The corpus is written by the project, so a high number says the checks find the defects the project already knew about.', '')
  L.push('## Summary', '')
  L.push(`- Planted defects: ${all.planted}`, `- Found by a check: ${all.found} (${pct(all.found, all.planted)})`, `- Missed: ${all.planted - all.found}`)
  const cleanN = data.totalLine?.twins ?? data.cleanProjects.length
  const faTotal = data.totalLine?.total ?? data.falseAlarms.length
  if (data.falseAlarmsRecorded) L.push(`- Clean-twin false alarms: ${faTotal} across ${cleanN} clean twins`)
  else L.push(`- Clean-twin false alarms: not recorded in this run output (${cleanN} clean twins were run, but the run prints no per-twin result)`)
  L.push('')
  L.push('## Recall by tier', '', '| Tier | Planted | Found | Recall |', '| --- | ---: | ---: | ---: |')
  for (const t of [...TIER_NAMES, ...(rows.some((r) => r.tier === 'untiered') ? ['untiered'] : [])]) {
    const s = tally(rows.filter((r) => r.tier === t))
    L.push(`| ${t} | ${s.planted} | ${s.found} | ${pct(s.found, s.planted)} |`)
  }
  L.push(`| **all** | ${all.planted} | ${all.found} | ${pct(all.found, all.planted)} |`, '')
  L.push('## Recall by suite', '', '| Suite | Planted | Found | Recall |', '| --- | ---: | ---: | ---: |')
  for (const s of [...new Set(rows.map((r) => r.suite))].sort()) {
    const t = tally(rows.filter((r) => r.suite === s))
    L.push(`| ${s} | ${t.planted} | ${t.found} | ${pct(t.found, t.planted)} |`)
  }
  L.push(`| **all** | ${all.planted} | ${all.found} | ${pct(all.found, all.planted)} |`, '')
  const missed = rows.filter((r) => r.status === 'MISS')
  L.push('## Missed defects', '')
  if (!missed.length) L.push('None.')
  else for (const r of missed) L.push(`- \`${r.key}\` (${r.tier}, ${r.suite}): expected \`${r.expected}\` at \`${r.file}:${r.line}\``)
  L.push('', '## False alarms on clean twins', '')
  if (data.falseAlarmsRecorded) {
    L.push('A clean twin is the same code written safely. A finding of critical, high or medium severity on one is counted as a false alarm; low and info findings are notes and not counted.', '')
    L.push(`Total: ${faTotal} false alarms across ${cleanN} clean twins.`, '')
    const per = Object.entries(data.perTwin).sort(([a], [b]) => a.localeCompare(b))
    if (per.length) L.push('| Clean twin | False alarms |', '| --- | ---: |', ...per.map(([t, n]) => `| ${t} | ${n} |`), '')
    L.push(...(data.falseAlarms.length ? data.falseAlarms.map((f) => `- ${f}`) : ['None.']))
  }
  else L.push(`This run output does not record false alarms. ${cleanN} clean twins (the same code written safely) were run: ${data.cleanProjects.join(', ') || 'none'}.`)
  L.push('', '## Every planted defect', '', 'Result: OK means a check reported it at the planted place, MISS means none did.', '')
  L.push('| Key | Tier | Suite | Expected check | Result |', '| --- | --- | --- | --- | --- |')
  for (const r of [...rows].sort((a, b) => a.suite.localeCompare(b.suite) || a.key.localeCompare(b.key))) L.push(`| \`${r.key}\` | ${r.tier} | ${r.suite} | \`${r.expected}\` | ${r.status} |`)
  L.push('')
  return L.join('\n')
}

export function renderReadme(data) {
  const all = tally(data.rows)
  const crit = tally(data.rows.filter((r) => r.tier === 'critical'))
  const hard = tally(data.rows.filter((r) => r.tier === 'hard'))
  return [
    '## Planted-bug accuracy',
    '',
    `Meerkat is tested against a corpus of ${all.planted} deliberately planted defects. In that run ${all.found} (${pct(all.found, all.planted)}) were detected by a check (the check's own verdict; the count in the findings file is in docs/accuracy.md); critical tier ${pct(crit.found, crit.planted)}, hard tier ${pct(hard.found, hard.planted)}.`,
    '',
    'Recall on planted bugs measures what was planted, not real-world accuracy.',
    '',
    'Every planted defect, its tier, suite and result is listed in [docs/accuracy-results.md](docs/accuracy-results.md).',
    '',
  ].join('\n')
}

async function main() {
  const argv = process.argv.slice(2)
  const opt = (n, d) => (argv.includes(n) ? argv[argv.indexOf(n) + 1] : d)
  const input = argv.find((a, i) => !a.startsWith('--') && !argv[i - 1]?.startsWith('--'))
  if (!input) {
    console.error('usage: node tools/gen-accuracy-results.mjs <run-output.txt> [--out file] [--readme file]')
    process.exit(2)
  }
  const data = await build(readFileSync(resolve(input), 'utf8'))
  if (!data.rows.length) {
    console.error('no OK/MISS lines found: was the run made with --run --discover?')
    process.exit(1)
  }
  const out = resolve(opt('--out', join(ROOT, 'docs', 'accuracy-results.md')))
  const readme = resolve(opt('--readme', join(ROOT, 'docs', 'readme-accuracy-section.md')))
  writeFileSync(out, render(data, basename(input)))
  writeFileSync(readme, renderReadme(data))
  console.log(`wrote ${out} and ${readme} (${data.rows.length} defects)`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main()
