// Generates the folder and entry-point part of MAP.md from the repo, between the markers <!-- map:start --> and <!-- map:end -->.
//   node tools/map/generate.mjs [--root <repo>] [--stdout]
// Reads tracked files only (git ls-files), so untracked files and node_modules never appear. Writes nothing but that marked block
// (creates MAP.md with a short hand-written stub if it does not exist). No counts are written: counts rot.
import { spawnSync } from 'node:child_process'
import { existsSync, openSync, readSync, closeSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import { dirname, join, resolve, extname, basename } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

export const START = '<!-- map:start -->'
export const END = '<!-- map:end -->'
const SKIP_FILES = new Set(['package-lock.json'])
const TEXT_EXT = new Set(['.mjs', '.js', '.cjs', '.ts', '.py', '.sh', '.md', '.yml', '.yaml', '.toml'])
const SMALL = 10

export function tracked(root) {
  const r = spawnSync('git', ['-C', root, 'ls-files', '-z'], { encoding: 'utf8', timeout: 30000, maxBuffer: 64 * 1024 * 1024 })
  if (r.status !== 0) throw new Error(`git ls-files failed in ${root}: ${r.stderr || r.error}`)
  return r.stdout.split('\0').filter(Boolean).filter((f) => existsSync(join(root, f))).sort()
}

function head(root, file) {
  try {
    const p = join(root, file)
    if (statSync(p).size === 0) return ''
    const fd = openSync(p, 'r')
    const buf = Buffer.alloc(4096)
    const n = readSync(fd, buf, 0, 4096, 0)
    closeSync(fd)
    return buf.toString('utf8', 0, n).replace(/^﻿/, '')
  } catch { return '' }
}

const clip = (s) => (s.length > 150 ? s.slice(0, 147) + '...' : s)
const tick = (s) => '`' + s + '`'

// The first comment block of a file, its first 2 non-empty lines, as one string. '' when there is none.
export function header(root, file) {
  const ext = extname(file).toLowerCase()
  if (!TEXT_EXT.has(ext)) return ''
  const lines = head(root, file).split(/\r?\n/)
  let i = 0
  if (lines[0] && lines[0].startsWith('#!')) i = 1
  while (i < lines.length && !lines[i].trim()) i++
  const out = []
  const l = (lines[i] || '').trim()
  if (ext === '.md') {
    const m = lines.find((x) => /^#\s+\S/.test(x))
    return m ? clip(m.replace(/^#\s+/, '')) : ''
  }
  if (l.startsWith('/*')) {
    for (; i < lines.length; i++) {
      const t = lines[i].replace(/^\s*\/\*+/, '').replace(/\*+\/\s*$/, '').replace(/^\s*\*\s?/, '').trim()
      if (t) out.push(t)
      if (lines[i].includes('*/') || out.length >= 2) break
    }
  } else {
    const mark = ['.py', '.sh', '.yml', '.yaml', '.toml'].includes(ext) ? '#' : '//'
    for (; i < lines.length && lines[i].trim().startsWith(mark); i++) {
      const t = lines[i].trim().replace(new RegExp('^' + mark + '+\\s?'), '').trim()
      if (t) out.push(t)
      if (out.length >= 2) break
    }
  }
  return clip(out.slice(0, 2).join(' '))
}

function describeFolder(root, dir, files) {
  const own = files.filter((f) => !f.slice(dir.length + 1).includes('/'))
  const subs = [...new Set(files.filter((f) => f.slice(dir.length + 1).includes('/')).map((f) => f.slice(dir.length + 1).split('/')[0]))].sort()
  const exts = [...new Set(files.map((f) => extname(f).toLowerCase()).filter(Boolean))].sort()
  const out = [`### ${tick(dir + '/')}`, '', `File types: ${exts.length ? exts.map(tick).join(', ') : 'none'}.`, '']
  const bullet = (name, h) => out.push(`- ${tick(name)}${h ? ': ' + h : ''}`)
  if (own.length <= SMALL) for (const f of own) bullet(basename(f), header(root, f))
  else {
    const groups = new Map()
    for (const f of own) {
      const b = basename(f)
      const m = b.match(/^([A-Za-z0-9_]+)[-.]/)
      const key = m ? m[1] : b
      if (!groups.has(key)) groups.set(key, [])
      groups.get(key).push(f)
    }
    for (const [key, fs] of [...groups].sort((a, b) => a[0].localeCompare(b[0]))) {
      if (fs.length === 1) bullet(basename(fs[0]), header(root, fs[0]))
      else {
        const first = fs.find((f) => header(root, f)) || fs[0]
        bullet(key + '-*', header(root, first))
      }
    }
  }
  for (const s of subs) {
    const sf = files.filter((f) => f.startsWith(`${dir}/${s}/`))
    const first = sf.find((f) => header(root, f))
    bullet(s + '/', first ? header(root, first) : '')
  }
  out.push('')
  return out.join('\n')
}

export function buildBlock(root) {
  const all = tracked(root).filter((f) => !SKIP_FILES.has(f))
  const dirs = [...new Set(all.filter((f) => f.includes('/')).map((f) => f.split('/')[0]))].sort()
  const lines = [START, '', '_Generated by `node tools/map/generate.mjs`. Do not edit between the markers; edit outside them._', '', '## Entry points', '']
  let pkg = {}
  try { pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) } catch { /* no package.json */ }
  const bins = typeof pkg.bin === 'string' ? { [pkg.name]: pkg.bin } : pkg.bin || {}
  for (const [n, p] of Object.entries(bins).sort()) lines.push(`- Command ${tick(n)}: ${tick(p)}${all.includes(p) && header(root, p) ? ': ' + header(root, p) : ''}`)
  if (all.includes('run.mjs')) lines.push(`- ${tick('run.mjs')}: ${header(root, 'run.mjs') || 'script entry (npm run meerkat)'}`)
  if (pkg.scripts) lines.push(`- ${tick('package.json')} scripts: ${Object.keys(pkg.scripts).sort().map(tick).join(', ')}`)
  for (const w of all.filter((f) => /^\.github\/workflows\/.+\.ya?ml$/.test(f))) {
    const nm = head(root, w).match(/^name:\s*(.+)$/m)
    lines.push(`- Workflow ${tick(w)}${nm ? ': ' + nm[1].trim() : ''}`)
  }
  lines.push('', '## Folders', '')
  for (const d of dirs) lines.push(describeFolder(root, d, all.filter((f) => f.startsWith(d + '/'))))
  lines.push(END)
  return lines.join('\n')
}

export function spliceBlock(existing, block) {
  const a = existing.indexOf(START)
  const b = existing.indexOf(END)
  if (a !== -1 && b > a) return existing.slice(0, a) + block + existing.slice(b + END.length)
  return existing.replace(/\s*$/, '\n\n') + block + '\n'
}

export function currentBlock(text) {
  const a = text.indexOf(START)
  const b = text.indexOf(END)
  return a !== -1 && b > a ? text.slice(a, b + END.length) : null
}

export const STUB = '# Map\n\nWhere things are in this repo and how the parts connect. The block below is generated; everything outside it is hand-written.\n'

function main() {
  const argv = process.argv.slice(2)
  let root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
  let stdout = false
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--root') root = resolve(argv[++i] || '')
    else if (argv[i] === '--stdout') stdout = true
    else { console.error('usage: node tools/map/generate.mjs [--root <repo>] [--stdout]'); process.exit(2) }
  }
  const block = buildBlock(root)
  if (stdout) { console.log(block); return }
  const file = join(root, 'MAP.md')
  const had = existsSync(file)
  const existing = had ? readFileSync(file, 'utf8') : STUB
  const next = spliceBlock(existing, block)
  if (next !== existing || !had) writeFileSync(file, next)
  console.log(`MAP.md block ${next === existing && had ? 'already current' : 'written'}: ${file}`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main()
