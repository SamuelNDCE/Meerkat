// The data-science checks (thorough/data-science.mjs): each check fails on its own fixture with a "found N" line, passes on a clean
// folder, reports "not applicable" when the folder has none of that kind, and the data-science pack loads with no bad-check-file.
import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { afterAll, describe, expect, test } from 'vitest'
import { loadChecks } from './lib/load-checks.mjs'

const ROOT = fileURLToPath(new URL('.', import.meta.url))
const SCRIPT = 'thorough/data-science.mjs'
const ALL = [
  'notebook-valid-json',
  'notebook-outputs-stripped',
  'notebook-secrets',
  'notebook-size',
  'notebook-absolute-paths',
  'notebook-pip-magics',
  'model-files-in-git',
  'data-files-in-git',
  'pickle-load',
  'random-seed-missing',
  'requirements-pinned-ml',
  'dataset-license-note',
]

const made: string[] = []
afterAll(() => {
  for (const d of made) rmSync(d, { recursive: true, force: true })
})

// Runs one check and returns its exit code and printed output (0 clean, 1 findings, 75 not run).
function runCheck(check: string, args: string[] = []): { code: number; out: string } {
  try {
    const out = execFileSync(process.execPath, [SCRIPT, check, ...args], { cwd: ROOT, stdio: 'pipe', encoding: 'utf8' })
    return { code: 0, out }
  } catch (e: any) {
    return { code: e.status ?? -1, out: `${e.stdout ?? ''}${e.stderr ?? ''}` }
  }
}

// A folder with the given files, and nothing else (no git, so the check walks the folder).
function folder(files: Record<string, string>): string {
  const dir = mkdtempSync(join(tmpdir(), 'meerkat-datascience-'))
  made.push(dir)
  for (const [name, body] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, name)), { recursive: true })
    writeFileSync(join(dir, name), body)
  }
  return dir
}

const nb = (cells: unknown[]) => JSON.stringify({ cells, metadata: { kernelspec: { name: 'python3' } }, nbformat: 4, nbformat_minor: 5 }, null, 1)
const code = (source: string, extra: Record<string, unknown> = {}) => ({ cell_type: 'code', metadata: {}, execution_count: null, outputs: [], source, ...extra })

describe('data-science checks fail on their own fixture', () => {
  for (const check of ALL) {
    test(`${check} reports its deliberate problem with a found line`, () => {
      const r = runCheck(check, ['--fixtures'])
      expect(r.code).toBe(1)
      expect(r.out).toMatch(/found \d+/)
    })
  }
})

describe('data-science checks say not applicable in an empty folder', () => {
  const dir = folder({ 'README.md': '# Empty\n\nNothing data-related here.\n' })
  test('notebook checks name the missing kind', () => {
    const r = runCheck('notebook-outputs-stripped', ['--root', dir])
    expect(r.code).toBe(0)
    expect(r.out).toContain('not applicable: no notebooks')
  })
  for (const check of ALL) {
    test(`${check} passes in an empty folder`, () => {
      expect(runCheck(check, ['--root', dir]).code).toBe(0)
    })
  }
})

describe('a clean ML project passes every check', () => {
  const dir = folder({
    'notebooks/clean.ipynb': nb([{ cell_type: 'markdown', metadata: {}, source: '# Title\n' }, code('import numpy as np\nnp.random.seed(0)\n')]),
    'train.py': 'import numpy as np\nnp.random.seed(0)\nfor epoch in range(3):\n    model.fit(X, y)\n',
    'requirements.txt': 'numpy==1.26.4\npandas==2.2.2\nscikit-learn==1.5.1\n',
    'data/README.md': 'Source: synthetic numbers generated by train.py.\n',
    'data/train.csv': 'a,b\n1,2\n',
  })
  for (const check of ALL) {
    test(`${check} is clean`, () => {
      const r = runCheck(check, ['--root', dir])
      expect(r.code).toBe(0)
    })
  }
})

describe('no false positives on Meerkat itself', () => {
  for (const check of ALL) {
    test(`${check} passes on the Meerkat repository`, () => {
      expect(runCheck(check, ['--root', ROOT]).code).toBe(0)
    })
  }
})

describe('the data-science pack', () => {
  test('loads 12 checks with no bad-check-file entries', async () => {
    const checks = await loadChecks(join(ROOT, 'packs', 'data-science'))
    expect(checks.filter((c) => c.id.startsWith('bad-check-file'))).toEqual([])
    expect(checks).toHaveLength(12)
    expect(checks.map((c) => c.id).sort()).toEqual([...ALL].sort())
    expect(checks.every((c) => c.suite === 'data-files' && c.tier === 'fast' && c.lane === 'free' && c.weight === 'tiny')).toBe(true)
  })
})
