// Electron and desktop-framework rule tables (the ep-* checks in thorough/electron-plus.mjs). Each table is one check. A rule is a
// line regex (`re`) or a `test(line, ctx)` function when it needs the surrounding lines or the whole file. Meerkat's own rules,
// written from the sources below. Every rule carries a bad and a good sample (selfProve in thorough/rules.mjs proves them).
//
// Sources read for this table (each rule's comment names the one it came from):
//   S  Electron security checklist, 20 numbered items: https://www.electronjs.org/docs/latest/tutorial/security
//   F  Electron Fuses: https://www.electronjs.org/docs/latest/tutorial/fuses
//   W  BrowserWindow webPreferences: https://www.electronjs.org/docs/latest/api/browser-window
//   SE session API: https://www.electronjs.org/docs/latest/api/session
//   WC webContents API: https://www.electronjs.org/docs/latest/api/web-contents
//   P  protocol API: https://www.electronjs.org/docs/latest/api/protocol
//   EB electron-builder config schema (packages/app-builder-lib/scheme.json, master branch, read 2026-10-31):
//      https://github.com/electron-userland/electron-builder/blob/master/packages/app-builder-lib/scheme.json
//   TC Tauri v2 config reference: https://v2.tauri.app/reference/config/ ; capabilities: https://v2.tauri.app/security/capabilities/ ;
//      CSP: https://v2.tauri.app/security/csp/
// Items the checklist recommends that no static rule can decide are listed in CHECKLIST_NOTES at the bottom, with the reason.
// Regexes are linear: bounded quantifiers ({0,200}) and no nested open spans, so a hostile 100 KB line cannot blow up.
// Rules that need a sibling line (for example a handler body) look only at a fixed window of lines after the match.

const JS = ['js', 'mjs', 'cjs', 'ts', 'mts', 'cts', 'jsx', 'tsx']
const HTML = ['html', 'htm']
const COMMENT = /^\s*(\/\/|\/\*|\*|<!--)/
// Tests, docs, examples, fixtures and vendored code: deliberate bad code lives there. The rule tables and the runner quote the
// dangerous calls as sample text, so they are excluded from their own scan.
const TEST_OUT = /(^|\/)(tests?|__tests__|spec|specs|examples?|docs?|fixtures?|testdata|vendor|third_party|benches?|node_modules)\/|\.(test|spec)\.[a-z]+$|(^|\/)(rules-electron-plus|electron-plus)\.mjs$|(^|\/)packs\/electron-plus\//i
const PKG = /(^|\/)package\.json$/
const BUILD = /(^|\/)(electron-builder\.[A-Za-z0-9]+|forge\.config\.[cm]?[jt]s)$/
const ENT = /(^|\/)[^/]*entitlements[^/]*\.plist$/i
const PLIST = /(^|\/)Info\.plist$/
const FUSES_SET = /FuseV1Options|flipFuses|electronFuses|@electron\/fuses/
const isBuildConfig = (file, text) => BUILD.test(file) || (PKG.test(file) && /"build"\s*:|"electron-builder"|"@electron-forge\//.test(text))

// Caches the answer for one file text: a whole-file predicate runs once even when a line test calls it for every matching line.
const memo = (fn) => {
  let last
  let val = false
  return (t) => {
    if (t !== last) {
      last = t
      val = fn(t)
    }
    return val
  }
}
// A line test: the line matches re AND the whole file satisfies pred(text).
const lineIf = (re, pred) => {
  const p = memo(pred)
  return (line, ctx) => re.test(line) && p(ctx.text)
}
// A once-per-file test (on the first line): pred(text, file) holds.
const fileIf = (pred) => (line, ctx) => ctx.index === 0 && pred(ctx.text, ctx.file)
// A line that matches re, with nre found in the window of lines from this one (inclusive) to n lines after it.
const near = (re, nre, n = 10) => (line, ctx) => re.test(line) && ctx.lines.slice(ctx.index, ctx.index + n + 1).some((l) => nre.test(l))
// A line that matches re, with nre NOT found in that window.
const notNear = (re, nre, n = 12) => (line, ctx) => re.test(line) && !ctx.lines.slice(ctx.index, ctx.index + n + 1).some((l) => nre.test(l))
// A plist key line whose value on the next line is <true/>.
const keyTrue = (key) => (line, ctx) => line.includes(`<key>${key}</key>`) && /<true\s*\/>/.test(ctx.lines[ctx.index + 1] ?? '')
// Which block header (dependencies or devDependencies) is the nearest one above this line.
const under = (ctx) => {
  for (let i = ctx.index - 1; i >= Math.max(0, ctx.index - 40); i--) {
    const m = /"(devDependencies|dependencies|optionalDependencies)"\s*:/.exec(ctx.lines[i])
    if (m) return m[1]
  }
  return ''
}

// A function passed where a regex goes is a line test (rules.mjs calls rule.test, not rule.re, when it is set).
const asRule = (re, extra) => (typeof re === 'function' ? { re: undefined, test: re, ...extra } : { re, ...extra })
const js = (id, title, re, bad, good, extra = {}) => ({ id, title, ext: JS, skipLine: COMMENT, notIn: TEST_OUT, bad, good, ...asRule(re, extra) })
const html = (id, title, re, bad, good, extra = {}) => ({ id, title, ext: HTML, notIn: TEST_OUT, bad, good, ...asRule(re, extra) })
const onFile = (files, sample) => (id, title, re, bad, good, extra = {}) => ({ id, title, files, sample, skipLine: COMMENT, notIn: TEST_OUT, bad, good, ...asRule(re, extra) })
const pkg = onFile(PKG, 'package.json')
const build = onFile(BUILD, 'electron-builder.json')
// Fuse setting in either spelling: `runAsNode: true` (electron-builder electronFuses) or `[FuseV1Options.RunAsNode]: true` (@electron/fuses).
// electron-builder's key for the ASAR integrity fuse is not confirmed in the schema read for this table, so both spellings count.
const FUSE_ALIAS = { embeddedAsarIntegrityValidation: 'enableEmbeddedAsarIntegrityValidation' }
const fuseIs = (camel, pascal, value) => {
  const alt = [`\\b${camel}\\s*:`, `\\b${pascal}\\]\\s*:`]
  if (FUSE_ALIAS[camel]) alt.push(`\\b${FUSE_ALIAS[camel]}\\s*:`)
  return new RegExp(`(?:${alt.join('|')})\\s*${value}\\b`)
}
const fuseNamed = (camel, pascal) => new RegExp(`\\b(?:${[camel, pascal, FUSE_ALIAS[camel]].filter(Boolean).join('|')})\\b`)

