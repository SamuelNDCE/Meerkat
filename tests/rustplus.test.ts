describe('every rule proves itself', () => {
  for (const id of IDS) {
    test(`${id}: bad sample is found, good sample is not, ids are unique`, () => {
      expect(selfProve(table(id))).toEqual([])
    })
  }
  test('each check ships at least one rule, and the ids carry a family prefix', () => {
    const all: string[] = []
    for (const id of IDS) {
      expect(table(id).length).toBeGreaterThan(0)
      all.push(...table(id).map((r: any) => r.id))
    }
    expect(new Set(all).size).toBe(all.length)
    expect(all.every((x) => /^(rsafe|rerr|rasync|rperf|rcargo|rapi)-/.test(x))).toBe(true)
  })
})

describe('each check fails on its own fixture', () => {
  for (const id of IDS) {
    test(`${id} --fixtures exits 1`, () => {
      expect(runCheck([id, '--fixtures']).code).toBe(1)
    })
  }
})

describe('a clean Rust crate passes every rule that applies', () => {
  const dir = tempDir(CLEAN_CRATE)
  for (const id of IDS) {
    test(`${id} exits 0 with one PASS or NA line per rule`, () => {
      const r = runCheck([id, '--root', dir])
      expect(r.code).toBe(0)
      const subs = r.out.split('\n').filter((l) => l.startsWith('MEERKAT-SUB '))
      expect(subs).toHaveLength(table(id).length)
      expect(subs.every((l) => /^MEERKAT-SUB (PASS|NA) /.test(l))).toBe(true)
    })
  }
})

describe('a project with no Rust reports NA for every rule', () => {
  const dir = tempDir({ 'app.py': 'print("hi")\n', 'README.md': '# app\n' })
  for (const id of IDS) {
    test(`${id} exits 0 with only NA lines`, () => {
      const r = runCheck([id, '--root', dir])
      expect(r.code).toBe(0)
      const subs = r.out.split('\n').filter((l) => l.startsWith('MEERKAT-SUB '))
      expect(subs.every((l) => l.startsWith('MEERKAT-SUB NA '))).toBe(true)
    })
  }
})

describe('hostile input stays fast', () => {
  const hostile = [
    'a'.repeat(100_000),
    '('.repeat(50_000) + 'a+'.repeat(20_000),
    'let x = '.repeat(12_000),
    'unsafe fn '.repeat(9_000),
    '"'.repeat(50_000) + 'x'.repeat(20_000),
    '.unwrap_or('.repeat(10_000),
    'pub struct '.repeat(9_000),
  ]
  for (const id of IDS) {
    test(`${id}: every rule finishes 7 hostile 100 KB lines in under 2 seconds`, () => {
      const started = Date.now()
      for (const r of table(id)) {
        for (const line of hostile) {
          const ctx = { file: 'x', lines: [line], index: 0, text: line }
          if (r.test) r.test(line, ctx)
          else r.re.test(line)
        }
      }
      expect(Date.now() - started).toBeLessThan(2000)
    })
  }
})

describe('the rust-plus pack', () => {
  test('loads one check per table with no bad-check-file entries, and subs match each table', async () => {
    const checks = await loadChecks(join(ROOT, 'packs', 'rust-plus'))
    expect(checks.filter((c) => c.id.startsWith('bad-check-file'))).toEqual([])
    expect(checks.map((c) => c.id).sort()).toEqual([...IDS].sort())
    for (const c of checks) expect(c.subs).toBe(table(c.id).length)
  })
})

describe('house style', () => {
  test('the new files have no em dashes or en dashes', () => {
    for (const f of NEW_FILES) {
      const text = readFileSync(join(ROOT, f), 'utf8')
      const dashes = [String.fromCharCode(0x2014), String.fromCharCode(0x2013)]
      expect(dashes.some((d) => text.includes(d)), f).toBe(false)
    }
  })
})
