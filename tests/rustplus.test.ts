// The rust-plus checks (thorough/rust-plus.mjs): every rule proves itself, each check fails on its own fixture, a realistic clean
// crate passes every rule that applies, a non-Rust project reports NA everywhere, regexes stay fast on hostile input, and the pack
// loads with no bad-check-file entries. The rule count is whatever ships: there is no minimum.
import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { afterAll, describe, expect, test } from 'vitest'
import { loadChecks } from '../lib/load-checks.mjs'
// @ts-expect-error plain JS module
import { selfProve } from '../thorough/rules.mjs'
// @ts-expect-error plain JS module
import { CHECK_TABLES } from '../thorough/rules-rust-plus.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const SCRIPT = 'thorough/rust-plus.mjs'
const NEW_FILES = ['thorough/rules-rust-plus.mjs', 'thorough/rust-plus.mjs', 'packs/rust-plus/rust-plus.mjs', 'rustplus.test.ts']
const made: string[] = []
afterAll(() => {
  for (const d of made) rmSync(d, { recursive: true, force: true })
})

const IDS = Object.keys(CHECK_TABLES) as string[]
const table = (id: string): any[] => CHECK_TABLES[id]

// Runs the check script; returns its exit code and its output (a crash is reported as code -1).
function runCheck(args: string[]): { code: number; out: string } {
  try {
    const out = execFileSync(process.execPath, [SCRIPT, ...args], { cwd: ROOT, stdio: 'pipe', encoding: 'utf8' })
    return { code: 0, out }
  } catch (e: any) {
    return { code: e.status ?? -1, out: String(e.stdout ?? '') + String(e.stderr ?? '') }
  }
}

function tempDir(files: Record<string, string>): string {
  const dir = mkdtempSync(join(tmpdir(), 'meerkat-rp-'))
  made.push(dir)
  for (const [name, body] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, name)), { recursive: true })
    writeFileSync(join(dir, name), body)
  }
  return dir
}

