// Cargo.lock scoping: when the only workspace-level change is Cargo.lock, rust-test runs just the crates whose resolved dependency set changed
// (plus their path dependents). Any other workspace-level change, or a lock that cannot be read, runs the whole workspace. No cargo runs: a fake runner stands in.
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterAll, describe, expect, test } from 'vitest'
// @ts-expect-error plain JS module
import { createControl, runAll } from '../lib/runner.mjs'
// @ts-expect-error plain JS module
import RUST from '../packs/rust/rust.mjs'

const made: string[] = []
afterAll(() => { for (const d of made) rmSync(d, { recursive: true, force: true }) })

const git = (root: string, ...a: string[]) => { const r = spawnSync('git', ['-C', root, '-c', 'user.name=t', '-c', 'user.email=t@t', '-c', 'commit.gpgsign=false', ...a], { encoding: 'utf8' }); if (r.status !== 0) throw new Error(r.stderr); return r.stdout.trim() }
function crate(root: string, name: string, deps: Record<string, string> = {}) {
  mkdirSync(join(root, name, 'src'), { recursive: true })
  const dep = Object.entries(deps).map(([n, p]) => `${n} = { path = "${p}" }`).join('\n')
  writeFileSync(join(root, name, 'Cargo.toml'), `[package]\nname = "${name}"\nversion = "0.1.0"\n\n[dependencies]\n${dep}\n`)
  writeFileSync(join(root, name, 'src', 'lib.rs'), '')
}
const pkg = (name: string, version: string, deps: string[] = [], src = false) =>
  `[[package]]\nname = "${name}"\nversion = "${version}"\n${src ? 'source = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "abc' + name + version + '"\n' : ''}${deps.length ? `dependencies = [\n${deps.map((d) => ` "${d}",`).join('\n')}\n]\n` : ''}`
const lock = (serde: string, order: 'a' | 'b' = 'a') => {
  const parts = [pkg('base', '0.1.0'), pkg('lone', '0.1.0', ['serde']), pkg('mid', '0.1.0', ['base', 'itoa']), pkg('itoa', '1.0.0', [], true), pkg('serde', serde, [], true)]
  return `# This file is automatically @generated by Cargo.\nversion = 3\n\n${(order === 'a' ? parts : [...parts].reverse()).join('\n')}`
}
// A three-crate workspace (base <- mid, lone independent) with Cargo.lock v1 committed as the base; returns the root and the base sha.
function ws() {
  const root = mkdtempSync(join(tmpdir(), 'meerkat-lock-')); made.push(root)
  git(root, 'init', '-q')
  writeFileSync(join(root, 'Cargo.toml'), '[workspace]\nmembers = ["base", "mid", "lone"]\n')
  crate(root, 'base'); crate(root, 'mid', { base: '../base' }); crate(root, 'lone')
  writeFileSync(join(root, 'Cargo.lock'), lock('1.0.0'))
  git(root, 'add', '-A'); git(root, 'commit', '-q', '-m', 'base')
  return { root, base: git(root, 'rev-parse', 'HEAD') }
}
const checkOf = (id: string) => ({ ...RUST.find((c: any) => c.id === id), needs: [] })
const ok = { code: 0, output: 'ok', killed: null, ms: 5, timedOut: false, subs: [], subsDropped: 0, findings: [], findingsDropped: 0 }
async function run(root: string, base: string, changedFiles: string[], id = 'rust-test') {
  const calls: string[][] = []
  const runCommand = async (o: any) => { calls.push(o.args.slice(o.args.indexOf('cargo') + 1)); return ok }
  const ctx = {
    timeoutScale: 1, repoRoot: root, appDir: root, tier: 'fast', env: { ...process.env, MEERKAT_BASE: base, MEERKAT_HOME: root, MEERKAT_LOG_DIR: join(root, 'logs') },
    platform: process.platform, exists: existsSync, changedFiles, disabledSubs: new Map(), findingsSink: new Map(), logDir: null, control: createControl(), runCommand,
  }
  const res = await runAll([checkOf(id)], ctx, { log: () => {}, keepGoing: true, parallel: 1 })
  return { calls, detail: JSON.stringify(res) }
}
const commitLock = (root: string, text: string) => { writeFileSync(join(root, 'Cargo.lock'), text); git(root, 'add', 'Cargo.lock'); git(root, 'commit', '-q', '-m', 'lock') }

describe('Cargo.lock only change', () => {
  test('(a) a bump of a dependency used only by "lone" runs cargo test -p lone, not the workspace', async () => {
    const { root, base } = ws()
    commitLock(root, lock('1.0.1'))
    const { calls, detail } = await run(root, base, ['Cargo.lock'])
    expect(calls).toHaveLength(1)
    expect(calls[0]).toEqual(['test', '-p', 'lone'])
    expect(detail).toContain('Cargo.lock')
  })
  test('(b) a reorder with no semantic change runs the documented minimum: cargo metadata --locked, no crate tests', async () => {
    const { root, base } = ws()
    commitLock(root, lock('1.0.0', 'b'))
    const { calls, detail } = await run(root, base, ['Cargo.lock'])
    expect(calls).toHaveLength(1)
    expect(calls[0]).toEqual(['metadata', '--locked', '--format-version', '1'])
    expect(detail).toContain('no resolved dependency changed')
  })
  test('a dependency used by base also runs its path dependent mid', async () => {
    const { root, base } = ws()
    commitLock(root, lock('1.0.0').replace('name = "itoa"\nversion = "1.0.0"', 'name = "itoa"\nversion = "1.0.1"'))
    const { calls } = await run(root, base, ['Cargo.lock'])
    expect(calls[0]).toEqual(['test', '-p', 'mid'])
  })
  test('(c) a Cargo.lock change together with the root Cargo.toml runs the whole workspace', async () => {
    const { root, base } = ws()
    commitLock(root, lock('1.0.1'))
    const { calls } = await run(root, base, ['Cargo.lock', 'Cargo.toml'])
    expect(calls[0]).toEqual(['test', '--workspace'])
  })
  test('(d) an unreadable old lock fails closed to the whole workspace with a reason', async () => {
    const { root } = ws()
    commitLock(root, lock('1.0.1'))
    const { calls, detail } = await run(root, 'no-such-ref', ['Cargo.lock'])
    expect(calls[0]).toEqual(['test', '--workspace'])
    expect(detail).toMatch(/old Cargo\.lock/)
  })
  test('(d) an unreadable new lock fails closed to the whole workspace with a reason', async () => {
    const { root, base } = ws()
    commitLock(root, lock('1.0.1'))
    writeFileSync(join(root, 'Cargo.lock'), 'this is not a lock file')
    const { calls, detail } = await run(root, base, ['Cargo.lock'])
    expect(calls[0]).toEqual(['test', '--workspace'])
    expect(detail).toMatch(/new Cargo\.lock/)
  })
})
